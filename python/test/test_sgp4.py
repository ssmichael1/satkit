class TestSGP4InitErrors:
    """How an element set that cannot be initialized is reported."""

    def test_list_with_errflag(self):
        good = sk.TLE.from_lines(ISS_2021)[0]
        bad = sk.TLE.from_lines(BAD_INIT)[0]
        xp = sk.TLE.from_lines(ISS_2021)[0]
        xp.ephem_type = 4
        times = [good.epoch, good.epoch + sk.duration(days=1)]
        p, v, err = sk.sgp4([good, bad, xp], times, errflag=True)
        assert p.shape == (3, 2, 3) and err.shape == (3, 2)
        assert np.all(err[0] == sk.sgp4_error.success)
        assert np.all(err[1] == sk.sgp4_error.perturb_eccen)
        assert np.all(err[2] == sk.sgp4_error.unsupported)
        assert np.all(np.isnan(p[1:])) and np.all(np.isnan(v[1:]))
        # the good element set is unaffected
        assert np.array_equal(p[0], sk.sgp4(good, times)[0])

    def test_list_without_errflag_raises(self):
        good = sk.TLE.from_lines(ISS_2021)[0]
        bad = sk.TLE.from_lines(BAD_INIT)[0]
        with pytest.raises(RuntimeError, match="element set 1 of the list"):
            sk.sgp4([good, bad], good.epoch)

    def test_single_matches_list(self):
        bad = sk.TLE.from_lines(BAD_INIT)[0]
        with pytest.raises(RuntimeError, match="SGP4 init error"):
            sk.sgp4(bad, bad.epoch)
        p, v, err = sk.sgp4(bad, bad.epoch, errflag=True)
        assert p.shape == (3,) and err.shape == (1,)
        assert np.all(np.isnan(p)) and err[0] == sk.sgp4_error.perturb_eccen
        assert int(sk.sgp4_error.unsupported) == 7

