class TestTLELoaders:
    """TLE.from_lines / from_file always return a list and locate bad records."""

    def test_one_tle_is_a_list(self):
        tles = sk.TLE.from_lines([ISS_NAME, *ISS_2021])
        assert isinstance(tles, list)
        assert len(tles) == 1
