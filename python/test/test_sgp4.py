class TestSGP4Cache:
    """The SGP4 initialization cached in a TLE never goes stale."""

    def test_setter_after_propagation(self):
        tle = sk.TLE.from_lines(ISS_2021)[0]
        tm = tle.epoch + sk.duration(minutes=90)
        sk.sgp4(tle, tm)
        tle.inclination = 97.0
        tle.mean_motion = 14.2
        fresh = sk.TLE.from_lines(ISS_2021)[0]
        fresh.inclination = 97.0
        fresh.mean_motion = 14.2
        assert np.array_equal(sk.sgp4(tle, tm)[0], sk.sgp4(fresh, tm)[0])

    def test_gravconst_after_propagation(self):
        tle = sk.TLE.from_lines(ISS_2021)[0]
        tm = tle.epoch + sk.duration(days=3)
        p72, _ = sk.sgp4(tle, tm)
        p84, _ = sk.sgp4(tle, tm, gravconst=sk.sgp4_gravconst.wgs84)
        p84_fresh, _ = sk.sgp4(sk.TLE.from_lines(ISS_2021)[0], tm, gravconst=sk.sgp4_gravconst.wgs84)
        assert np.array_equal(p84, p84_fresh)
        assert np.linalg.norm(p84 - p72) > 10.0
        # the same in the list form
        p84_list, _ = sk.sgp4([tle], tm, gravconst=sk.sgp4_gravconst.wgs84)
        assert np.array_equal(p84_list[0], p84_fresh)

    def test_equality_after_propagation(self):
        tle = sk.TLE.from_lines(ISS_2021)[0]
        copied = copy.deepcopy(tle)
        sk.sgp4(tle, tle.epoch)
        assert tle == copied
        assert tle == pickle.loads(pickle.dumps(tle))
        assert tle == sk.TLE.from_lines(ISS_2021)[0]

    def test_type4_after_propagation(self):
        tle = sk.TLE.from_lines(ISS_2021)[0]
        sk.sgp4(tle, tle.epoch)
        tle.ephem_type = 4
        with pytest.raises(RuntimeError, match="SGP4-XP"):
            sk.sgp4(tle, tle.epoch)


